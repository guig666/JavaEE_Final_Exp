package com.konsonx.po;

/**
 * =====================================================
 * 用户实体类（PO）
 * =====================================================
 * 功能说明：
 * 1. 对应数据库中的user表
 * 2. 由MyBatis Generator自动生成（部分字段手动扩展）
 * 3. 用于封装普通用户（C端用户）的账号、余额等信息
 * =====================================================
 *
 * 数据库表结构（user）：
 * - user_id       INT         主键，自增，用户唯一标识
 * - user_phone    VARCHAR     用户手机号（登录账号，应唯一）
 * - user_alias    VARCHAR     用户昵称（显示名称）
 * - user_password VARCHAR     用户登录密码（当前为明文存储，生产环境建议加密）
 * - user_balance  REAL/FLOAT  用户账户余额（单位：元，支持充值/消费）
 * =====================================================
 */
public class User {

    /**
     * =====================================================
     * 用户ID（主键）
     * =====================================================
     * 说明：
     * - 数据库自增主键
     * - 唯一标识一个用户
     * - 用于充值、扣费、查询详情等业务操作
     */
    private Integer user_id;

    /**
     * =====================================================
     * 用户手机号
     * =====================================================
     * 说明：
     * - 作为登录账号使用
     * - 业务层面应保证唯一性
     * - 用于登录验证、按手机号搜索
     */
    private String user_phone;

    /**
     * =====================================================
     * 用户昵称
     * =====================================================
     * 说明：
     * - 前端展示用名称
     * - 可重复，不要求唯一
     * - 支持按昵称模糊搜索
     */
    private String user_alias;

    /**
     * =====================================================
     * 用户密码
     * =====================================================
     * 说明：
     * - 登录时验证的密码
     * - 当前为明文存储（建议生产环境使用MD5/SHA等加密）
     * - 返回前端时必须清空此字段（安全性考虑）
     */
    private String user_password;

    /**
     * =====================================================
     * 用户余额
     * =====================================================
     * 说明：
     * - 账户可用余额（单位：元）
     * - 支持充值（增加）和消费（减少）
     * - 扣费时需要校验余额是否充足（不能为负数）
     */
    private Float user_balance;

    /**
     * =====================================================
     * 获取用户ID
     * =====================================================
     * @return 用户ID（主键）
     */
    public Integer getUser_id() {
        return user_id;
    }

    /**
     * =====================================================
     * 设置用户ID
     * =====================================================
     * @param user_id 用户ID（主键）
     */
    public void setUser_id(Integer user_id) {
        this.user_id = user_id;
    }

    /**
     * =====================================================
     * 获取用户手机号
     * =====================================================
     * @return 用户手机号（登录账号）
     */
    public String getUser_phone() {
        return user_phone;
    }

    /**
     * =====================================================
     * 设置用户手机号
     * =====================================================
     * @param user_phone 用户手机号
     */
    public void setUser_phone(String user_phone) {
        this.user_phone = user_phone;
    }

    /**
     * =====================================================
     * 获取用户昵称
     * =====================================================
     * @return 用户昵称（展示名称）
     */
    public String getUser_alias() {
        return user_alias;
    }

    /**
     * =====================================================
     * 设置用户昵称
     * =====================================================
     * @param user_alias 用户昵称
     */
    public void setUser_alias(String user_alias) {
        this.user_alias = user_alias;
    }

    /**
     * =====================================================
     * 获取用户密码
     * =====================================================
     * @return 用户密码
     */
    public String getUser_password() {
        return user_password;
    }

    /**
     * =====================================================
     * 设置用户密码
     * =====================================================
     * @param user_password 用户密码
     */
    public void setUser_password(String user_password) {
        this.user_password = user_password;
    }

    /**
     * =====================================================
     * 获取用户余额
     * =====================================================
     * @return 用户账户余额（单位：元）
     */
    public Float getUser_balance() {
        return user_balance;
    }

    /**
     * =====================================================
     * 设置用户余额
     * =====================================================
     * @param user_balance 用户账户余额
     */
    public void setUser_balance(Float user_balance) {
        this.user_balance = user_balance;
    }
}