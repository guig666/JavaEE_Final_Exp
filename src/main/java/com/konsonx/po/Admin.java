package com.konsonx.po;

/**
 * =====================================================
 * 管理员实体类（PO）
 * =====================================================
 * 功能说明：
 * 1. 对应数据库中的admin表
 * 2. 由MyBatis Generator自动生成
 * 3. 用于封装管理员账号信息
 * =====================================================
 *
 * 数据库表结构（admin）：
 * - admin_id       INT         主键，自增，管理员唯一标识
 * - admin_account  VARCHAR     管理员登录账号
 * - admin_password VARCHAR     管理员登录密码（当前为明文存储，生产环境建议加密）
 * =====================================================
 */
public class Admin {

    /**
     * =====================================================
     * 管理员ID（主键）
     * =====================================================
     * 说明：
     * - 数据库自增主键
     * - 唯一标识一个管理员
     * - 通常用于关联查询、删除、更新操作
     */
    private Integer admin_id;

    /**
     * =====================================================
     * 管理员账号
     * =====================================================
     * 说明：
     * - 登录时使用的账号
     * - 应保证唯一性（业务层面控制）
     * - 用于登录验证、账号搜索
     */
    private String admin_account;

    /**
     * =====================================================
     * 管理员密码
     * =====================================================
     * 说明：
     * - 登录时验证的密码
     * - 当前为明文存储（建议生产环境使用MD5/SHA等加密）
     * - 返回前端时应清空此字段（安全性考虑）
     */
    private String admin_password;

    /**
     * =====================================================
     * 获取管理员ID
     * =====================================================
     * @return 管理员ID（主键）
     */
    public Integer getAdmin_id() {
        return admin_id;
    }

    /**
     * =====================================================
     * 设置管理员ID
     * =====================================================
     * @param admin_id 管理员ID（主键）
     */
    public void setAdmin_id(Integer admin_id) {
        this.admin_id = admin_id;
    }

    /**
     * =====================================================
     * 获取管理员账号
     * =====================================================
     * @return 管理员账号
     */
    public String getAdmin_account() {
        return admin_account;
    }

    /**
     * =====================================================
     * 设置管理员账号
     * =====================================================
     * @param admin_account 管理员账号
     */
    public void setAdmin_account(String admin_account) {
        this.admin_account = admin_account;
    }

    /**
     * =====================================================
     * 获取管理员密码
     * =====================================================
     * @return 管理员密码
     */
    public String getAdmin_password() {
        return admin_password;
    }

    /**
     * =====================================================
     * 设置管理员密码
     * =====================================================
     * @param admin_password 管理员密码
     */
    public void setAdmin_password(String admin_password) {
        this.admin_password = admin_password;
    }
}